let a=50;


console.log(a); // Output: 50    

console.log("Sum =", a + 3);

console.log("Sub =", a - 3); // Output: 47

console.log("Mul =", a * 2); // Output: 100

console.log("Div =", a / 4); // Output: 2.5

console.log("Mod =", a % 3); // Output: 2

console.log("Exp =", a ** 3); // Output: 125000

console.log("Post Increment =", a++); // Output: 50 (post-increment, a becomes 51 after this line)

console.log("Pre Increment =", ++a); // Output: 51 (pre-increment, a becomes 51 before this line)   

console.log("Post Decrement =", a--); // Output: 51 (post-decrement, a becomes 50 after this line)

console.log("Pre Decrement =", --a); // Output: 50 (pre-decrement, a becomes 50 before this line) 
